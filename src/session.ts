import { createWriteStream, readFileSync, WriteStream } from 'fs';
import * as path from 'path';

import { env } from './config/env';
import {
  ConnectionStatus,
  CurrentProtocolVersion,
  DataType,
  MessageType,
  Peer,
  RecordedFileEntry
} from './types/types';
import {
  updateActiveSessionStatus,
  updateCurrentActiveUsers,
  updateCurrentHost,
  updateUsage
} from './adminApi';
import { LDEBUG, LERROR } from './utils';

/**
 * A named room that manages a group of connected peers. One peer may act as the host,
 * controlling what all participants see, which simulation time is used, and which Lua
 * scripts execute on all connected OpenSpace instances.
 */
export class Session {
  /**
   * The unique name of this session. Peers must must provide this name during
   * authentication to join. Maximum 255 ASCII characters.
   */
  private name: string;

  /**
   * The clear-text password that peers need to provide to connect. This password has a
   * maximum length of 65535 characters and can consist only of ASCII characters. An empty
   * string means the room is public and any password is accepted.
   */
  private password: string;

  /**
   * The clear-text password for assuming hostship. The host password can have a maximum
   * length of 65535 characters and can consist only of ASCII characters.
   */
  private hostPassword: string;

  /**
   * A unique ID for this session, generated by the Firebase database provider.
   */
  private id: string | null = null;

  /**
   * The list of all peers currently connected to this session. Peers are appended on
   * successful authentication and removed when they disconnect or produce an error.
   */
  private peers: Peer[] = [];

  /**
   * The id of the current host. Note that this is **not** the location of this peer in
   * the `peers` list, but its `id`, which might be different under some circumstances.
   */
  private currentHostId: number | null = null;

  /**
   * In-memory buffer of previously received Data messages from the host. The entries
   * represent the latest authoritative session state and are replayed to newly connected
   * peers so they can synchronize before receiving live updates.
   */
  private recordedEntries: Buffer[] = [];

  /**
   * File stream used to persist host Data messages for recording and playback.
   *
   * Each incoming Data message from the host is serialized and appended to disk
   * together with a relative timestamp (milliseconds since the start of the current
   * recording segment).
   *
   * Binary layout per entry:
   * [double (64-bit) elapsedMs][uint32 payloadLength][payload bytes]
   */
  private recordingStream: WriteStream | null = null;

  /**
   * Elapsed ms accumulated in previous runs (0 for a brand-new session, restored from
   * last entry in the file when resuming)
   */
  private recordingElapsedOffsetMs: number = 0;

  /**
   * Wall-clock time when the first entry of this process run was recorded. A session
   * without a host does not start its clock.
   */
  private recordingSegmentStartMs: number | null = null;

  /**
   * Creates a new Session.
   *
   * @param name The unique name of this session
   * @param password The password peers must provide to join. Maximum 65535 ASCII
   *                 characters.
   * @param hostPassword The password peers must provide to claim hostship. Maximum 65535
   *                     ASCII characters.
   * @param id The unique ID assigned by the Firebase database provider, or null if not
   *           yet set
   */
  constructor(
    name: string,
    password: string | null,
    hostPassword: string,
    id: string | null = null
  ) {
    this.name = name;
    this.password = password ?? '';
    this.hostPassword = hostPassword;
    if (id) {
      this.id = id;
      this.resumeRecording();
    }
  }

  /**
   * @return The metadata of this session
   */
  public getSessionMetadata() {
    return {
      sessionName: this.name,
      password: this.password,
      hostPassword: this.hostPassword,
      id: this.id
    };
  }

  /**
   * Sets the unique ID of this session.
   *
   * @param id The unique ID assigned to this session
   */
  public setSessionID(id: string): void {
    this.id = id;
  }

  /**
   * Forcibly closes the session, disconnecting all connected peers.
   */
  public stop(): Promise<void> {
    this.stopRecording();

    return new Promise((resolve) => {
      if (this.peers.length === 0) {
        resolve();
        return;
      }

      // Create a copy of the peers since `this.peers` can be mutated concurrently by the
      // Wormhole socket 'error' callback while we're still iterating here
      const peersToDisconnect = [...this.peers];
      const settled = new Set<number>();

      const checkAllDisconnected = (peer: Peer) => {
        // A peer's disconnect may be reported twice, once here and via the socket-level
        // 'error' handler set up in the Wormhole
        if (settled.has(peer.id)) {
          return;
        }

        settled.add(peer.id);
        if (settled.size === peersToDisconnect.length) {
          resolve();
        }
      };

      for (const peer of peersToDisconnect) {
        // Handle if socket does not end properly
        peer.socket.once('error', (err) => {
          LDEBUG(
            `Session ${this.id}: error disconnecting peer #${peer.id} ('${peer.name}')`,
            err
          );
          checkAllDisconnected(peer);
        });

        peer.socket.end(() => {
          checkAllDisconnected(peer);
        });
      }
    });
  }

  /**
   * Handles the disconnection of a peer. We remove the peer from the list of connected
   * peers and free up the ID slot. If the peer that disconnected was the host, we inform
   * all connected peers that they no longer have a host.
   *
   * @param peer The peer that just disconnected
   */
  public onEnd(peer: Peer): void {
    // Find the index in the peer list of the peer that disconnected
    const idx = this.peers.findIndex((p: Peer) => p.id === peer.id);
    if (idx === -1) {
      LERROR(
        `Session '${this.id}': could not find peer with id #${peer.id} ` +
          `('${peer.name}') on disconnect`
      );
      return;
    }
    this.peers.splice(idx, 1);

    // Remove hostship if the host disconnected
    if (peer.id === this.currentHostId) {
      this.removeHostship();
    }

    // Update the number of connections
    this.sendNumberOfConnections();

    LDEBUG(`Session '${this.id}': ${this.peers.length} connection(s) remaining`);
  }

  /**
   * Handle incoming data from the provided peer, we only forward the data along to other
   * peers if it comes from the host.
   *
   * @param data The payload of the data message
   * @param peer The peer from which this message is coming
   */
  public handleData(data: Buffer, peer: Peer): void {
    // Check if this peer is the current host
    if (peer.id === this.currentHostId) {
      if (peer.status !== ConnectionStatus.Host) {
        LERROR(
          `Session '${this.id}': peer #${peer.id} ('${peer.name}')  matches ` +
            `currentHostId but has status ${peer.status}, expected Host ` +
            `(${ConnectionStatus.Host})`
        );
      }

      this.recordEntry(data);

      const message = this.buildMessage(MessageType.Data, data);
      this.peers.forEach((peer: Peer) => {
        if (peer.status === ConnectionStatus.ClientWithHost) {
          this.writeMessage(peer, message);
        }
      });
    }
  }

  /**
   * Handles an incoming hostship request message by the peer. If the message contains the
   * correct host password, the peer is promoted to hostship and the previous host is
   * demoted.
   *
   * @param data The payload of the hostship request message
   * @param peer The peer from which this message arrived
   */
  public handleHostshipRequest(data: Buffer, peer: Peer): void {
    LDEBUG(`Session '${this.id}': peer #${peer.id} ('${peer.name}') requested hostship`);

    const dv = new DataView(data.buffer, data.byteOffset, data.byteLength);
    let offset = 0;

    const passwordLength = dv.getUint16(offset, true);
    offset += Uint16Array.BYTES_PER_ELEMENT;
    if (passwordLength === 0) {
      // No password was given so we don't do anything
      LDEBUG(`Session '${this.id}': invalid host password length`);
      return;
    }

    const password = data.subarray(offset, offset + passwordLength).toString('utf-8');
    if (password !== this.hostPassword) {
      // Wrong password so we don't do anything
      LDEBUG(
        `Session '${this.id}': peer #${peer.id} ('${peer.name}') provided incorrect ` +
          `host password`
      );
      return;
    }

    if (peer.id === this.currentHostId) {
      LDEBUG(`Session '${this.id}': peer #${peer.id} ('${peer.name}') is already host`);
      return;
    }

    this.assignHost(peer);
  }

  /**
   * Handles an incoming hostship resignation by the peer. If the peer is the current
   * host, we remove the hostship and inform all connected peers that they lost their
   * host.
   *
   * @param peer The peer from which this message arrived
   */
  public handleHostshipResignation(peer: Peer): void {
    LDEBUG(`Session '${this.name}': peer #${peer.id} ('${peer.name}') resigned hostship`);

    // Only remove the host if it was the host peer that requested the resignation
    if (peer.status === ConnectionStatus.Host) {
      this.removeHostship();
    }
  }

  /**
   * Checks whether the provided password grants access to this session. Any empty room
   * password means the room is public and any password is accepted.
   *
   * @param password The room password provided by the peer
   * @return True if the password is correct, false otherwise
   */
  public isPasswordValid(password: string): boolean {
    return this.password === '' || password === this.password;
  }

  /**
   * Registers an already-validated peer into the session: adds it to the list of
   * connected peers, and promotes it to host if it provided the correct host password and
   * no host is currently assigned. The caller is responsible for having confirmed the
   * room password, and an existing `peer.id` already being set.
   *
   * @param peer The peer to register
   * @param hostPassword The host password provided by the peer, or null if none was given
   */
  public registerPeer(peer: Peer, hostPassword: string | null): void {
    // Bring the peer up-to speed on the latest state changes
    this.replayRecordedEntries(peer);

    // We can add this peer to the list of all peers in the group
    this.peers.push(peer);

    // If there is currently no host and this peer provided the host password we promote
    // them to hostship
    if (this.currentHostId === null && hostPassword === this.hostPassword) {
      LDEBUG(
        `Session '${this.name}': peer #${peer.id} ('${peer.name}') promoted to host`
      );
      this.assignHost(peer);
    } else {
      LDEBUG(
        `Session '${this.name}': peer #${peer.id} ('${peer.name}') registered as client`
      );
      peer.status =
        this.currentHostId === null
          ? ConnectionStatus.ClientWithoutHost
          : ConnectionStatus.ClientWithHost;

      this.sendConnectionStatus(peer);
    }

    this.sendNumberOfConnections();
    updateUsage(this.id!);
  }

  /**
   * Starts a new, empty recording file for this session and opens it for writing.
   */
  public startRecording(): void {
    this.recordingStream = createWriteStream(this.recordingFilePath(), { flags: 'w' });
    this.recordingStream.on('error', (error) => {
      LERROR(`Session '${this.id}': recording stream error`, error);
    });
  }

  /**
   * Loads an existing recording file's entries into memory and reopens the file for
   * writing (appending).
   */
  private resumeRecording(): void {
    try {
      const fileData = readFileSync(this.recordingFilePath());
      const entries = this.parseRecordingEntries(fileData);

      for (const entry of entries) {
        if (entry.data.readUint8(0) === DataType.Script) {
          this.recordedEntries.push(Buffer.from(entry.data));
        }
      }

      if (entries.length > 0) {
        this.recordingElapsedOffsetMs = entries[entries.length - 1].elapsedMs;
      }
    } catch (error) {
      LERROR(
        `Session '${this.id}': failed to load existing recording file '${this.recordingFilePath()}'`,
        error
      );
    }

    this.recordingStream = createWriteStream(this.recordingFilePath(), { flags: 'a' });
    this.recordingStream.on('error', (error) => {
      LERROR(`Session '${this.id}': recording stream error`, error);
    });
  }

  /**
   * Stop recording entries and close the recording file.
   */
  private stopRecording(): void {
    if (this.recordingStream) {
      this.recordingStream.end();
      this.recordingStream = null;
    }
  }

  /**
   * @param id The session ID to compute the recording file path for
   * @returns The path to that session's recording file on disk
   */
  public static recordingFilePathFor(id: string): string {
    return path.join(env.SESSION_RECORDING_DIR, `${id}.astrorec`);
  }

  /**
   * @returns The path to this session's recording file on disk
   */
  private recordingFilePath(): string {
    return Session.recordingFilePathFor(this.id!);
  }

  /**
   * Parses a recording file's contents into individual entries. Each entry on disk is
   * stored as: a double elapsed-ms field, a uint32 length prefix followed by that many
   * bytes of the raw Data payload.
   *
   * @param buffer The full contents of the recording file
   * @returns The list of individual entry buffers, in original order
   */
  private parseRecordingEntries(buffer: Buffer): RecordedFileEntry[] {
    const entries: RecordedFileEntry[] = [];
    let offset = 0;

    const headerSize = Float64Array.BYTES_PER_ELEMENT + Uint32Array.BYTES_PER_ELEMENT;
    while (offset + headerSize <= buffer.byteLength) {
      const elapsedMs = buffer.readDoubleLE(offset);
      offset += Float64Array.BYTES_PER_ELEMENT;

      const length = buffer.readUInt32LE(offset);
      offset += Uint32Array.BYTES_PER_ELEMENT;

      if (offset + length > buffer.byteLength) {
        LERROR(
          `Session '${this.id}': recording file ends with a truncated entry, discarding it`
        );
        break;
      }

      entries.push({ elapsedMs, data: buffer.subarray(offset, offset + length) });
      offset += length;
    }

    return entries;
  }

  /**
   * Record the given data entry to file on disk, tagged with the time elapsed since
   * recording started. Script events are also stored in RAM for late-joining peers.
   * Camera and Time updates will be receieved immediately upon joining and are therefore
   * excluded from RAM cache.
   *
   * @param data The raw Data message payload (dataType + timestamp + type-specific data)
   */
  private recordEntry(data: Buffer): void {
    if (!this.recordingStream) {
      LERROR(`Session '${this.id}': dropped recording entry, recording stream not open`);
      return;
    }
    const entry = Buffer.from(data);

    const header = Buffer.alloc(
      Float64Array.BYTES_PER_ELEMENT + Uint32Array.BYTES_PER_ELEMENT
    );
    header.writeDoubleLE(this.currentElapsedMs(), 0);
    const offset = Float64Array.BYTES_PER_ELEMENT;
    header.writeUInt32LE(entry.byteLength, offset);
    this.recordingStream.write(Buffer.concat([header, entry]));

    // Store only Scripts events in RAM
    const dataType = data.readUInt8(0);
    if (dataType === DataType.Script) {
      this.recordedEntries.push(entry);
    }
  }

  /**
   * Sends all recorded Script data messages directly to the given peer, in original
   * order, to bring a newly-joined peer up to date with state changes that happened before
   * they connected.
   *
   * @param peer The newly-joining peer to catch up
   */
  private replayRecordedEntries(peer: Peer): void {
    if (this.recordedEntries.length === 0) {
      return;
    }

    LDEBUG(
      `Session '${this.id}': replaying ${this.recordedEntries.length} recorded ` +
        `entries to peer #${peer.id} ('${peer.name}')`
    );

    for (const entry of this.recordedEntries) {
      this.sendMessage(peer, MessageType.Data, entry);
    }
  }

  /**
   * @return The number of milliseconds since recording started for this session. Time 0
   * is the first Data message ever recorded for the session, it is not reset by host
   * disconnecting and/or reconnecting. If the server restarts mid-session, the downtime
   * itself is not counted, i.e., elapsed time picks up where the previous run left off.
   */
  private currentElapsedMs(): number {
    if (this.recordingSegmentStartMs === null) {
      this.recordingSegmentStartMs = Date.now();
    }

    return this.recordingElapsedOffsetMs + (Date.now() - this.recordingSegmentStartMs);
  }

  /**
   * Construct a complete message buffer including the message header and provided payload
   * data.
   *
   * @param messageType The type of message to construct
   * @param payload The payload of the message
   * @return A buffer object holding the constructed message
   */
  private buildMessage(messageType: MessageType, payload: Buffer): Buffer {
    const buffer = Buffer.alloc(
      'OS'.length + // OS prefix
        Uint8Array.BYTES_PER_ELEMENT + // protocol version number
        Uint8Array.BYTES_PER_ELEMENT + // message type identifier
        Uint32Array.BYTES_PER_ELEMENT + // payload size in bytes
        payload.byteLength // payload
    );

    const dv = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
    let offset = 0;

    // Set OS header
    dv.setUint8(offset, 'OS'.charCodeAt(0));
    offset += Uint8Array.BYTES_PER_ELEMENT;
    dv.setUint8(offset, 'OS'.charCodeAt(1));
    offset += Uint8Array.BYTES_PER_ELEMENT;

    // Protocol version
    dv.setUint8(offset, CurrentProtocolVersion);
    offset += Uint8Array.BYTES_PER_ELEMENT;

    // Message type
    dv.setUint8(offset, messageType);
    offset += Uint8Array.BYTES_PER_ELEMENT;

    // Message size
    dv.setUint32(offset, payload.byteLength, true);
    offset += Uint32Array.BYTES_PER_ELEMENT;

    // Copy the payload into the message
    payload.copy(buffer, offset);
    return buffer;
  }

  /**
   * Write the `message` to the provided `peer`.
   *
   * @param peer The peer that will receive the message
   * @param message The message payload data that is sent
   */
  private writeMessage(peer: Peer, message: Buffer): void {
    LDEBUG(`Session '${this.id}': sending message to peer #${peer.id} ('${peer.name}')`);
    peer.socket.write(message);
  }

  /**
   * Send a message to the provided peer of the provided `messageType` with the specified
   * `payload` data.
   *
   * @param peer The peer that will receive the message
   * @param messageType The type of message that will be sent
   * @param payload The payload of the data that is sent
   */
  private sendMessage(peer: Peer, messageType: MessageType, payload: Buffer): void {
    this.writeMessage(peer, this.buildMessage(messageType, payload));
  }

  /**
   * Send a connection status message to the provided peer.
   *
   * @param peer The peer that will receive the connection status message
   */
  private sendConnectionStatus(peer: Peer): void {
    const host = this.currentHost();
    const currentHostName = host === null ? '' : host.name;

    const buffer = Buffer.alloc(
      Uint8Array.BYTES_PER_ELEMENT + // Status
        Uint8Array.BYTES_PER_ELEMENT + // Length of host
        currentHostName.length // Host name
    );

    const dv = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
    let offset = 0;

    // Set the connection status of the peer as known by the server
    dv.setUint8(offset, peer.status);
    offset += Uint8Array.BYTES_PER_ELEMENT;

    // The length of the host name
    dv.setUint8(offset, currentHostName.length);
    offset += Uint8Array.BYTES_PER_ELEMENT;

    // Insert the name of the current host
    buffer.write(currentHostName, offset, 'ascii');

    this.sendMessage(peer, MessageType.ConnectionStatus, buffer);
  }

  /**
   * Send the number of connections to all connected peers.
   */
  private sendNumberOfConnections(): void {
    LDEBUG(`Session '${this.id}': sending number of connections to all peers`);

    const buffer = Buffer.alloc(Uint32Array.BYTES_PER_ELEMENT); // Number of connections
    const dv = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
    dv.setUint32(0, this.peers.length, true);

    const message = this.buildMessage(MessageType.NConnections, buffer);
    this.peers.forEach((peer: Peer) => this.writeMessage(peer, message));
    // Update the server status depending on if there still are any users connected
    const isServerActive = this.peers.length > 0;
    updateActiveSessionStatus(this.id!, isServerActive);
    updateCurrentActiveUsers(this.id!, this.peers.length);
  }

  /**
   * @return The current host of the group or null if there is no host assigned
   */
  private currentHost(): Peer | null {
    if (this.currentHostId === null) {
      return null;
    }

    const idx = this.peers.findIndex((peer: Peer) => peer.id === this.currentHostId);
    if (idx === -1) {
      LDEBUG(`Session '${this.id}': could not find host with id ${this.currentHostId}`);
      return null;
    }

    return this.peers[idx];
  }

  /**
   * Mark the provided newHost peer as the new host of the group and remove the hostship
   * of the previous host. Inform all connected peers about the change in hostship.
   *
   * @param newHost The peer to be promoted to the new host
   */
  private assignHost(newHost: Peer): void {
    // If we currently have a host, we need to demote them
    if (this.currentHostId !== null) {
      const oldHost = this.currentHost()!; // Host id cannot be null here
      oldHost.status = ConnectionStatus.ClientWithHost;
    }

    // Promote the provided peer to host
    this.currentHostId = newHost.id;
    newHost.status = ConnectionStatus.Host;

    // Update others about the new host
    this.peers.forEach((peer: Peer) => {
      // If there was no host before, let them know about the new host
      if (peer.status === ConnectionStatus.ClientWithoutHost) {
        peer.status = ConnectionStatus.ClientWithHost;
      }
      this.sendConnectionStatus(peer);
    });

    updateCurrentHost(this.id!, newHost.name);
  }

  /**
   * If the group has a host, we remove the hostship and inform all connected peers that
   * there is no host anymore.
   */
  private removeHostship(): void {
    // If we don't have a host, we don't need to do anything
    if (this.currentHostId === null) {
      return;
    }

    // Remove host information on server side
    this.currentHostId = null;

    // Inform all peers that we no longer have a host, this includes the recently
    // removed host as well
    this.peers.forEach((peer: Peer) => {
      peer.status = ConnectionStatus.ClientWithoutHost;
      this.sendConnectionStatus(peer);
    });

    updateCurrentHost(this.id!, '');
  }
}
